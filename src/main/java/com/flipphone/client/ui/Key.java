package com.flipphone.client.ui;

/** The buttons of the phone. */
public enum Key {
    UP, DOWN, LEFT, RIGHT,
    /** Centre of the d-pad / Enter */
    OK,
    /** The soft keys under the screen (left label / right label) */
    LEFT_SOFT, RIGHT_SOFT,
    /** Backspace: goes back, or deletes a character while typing */
    BACK,
    /** M: jumps to the app menu */
    MENU
}
